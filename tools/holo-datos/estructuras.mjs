#!/usr/bin/env node
/**
 * Build-time preprocessing of the real molecular structures used by the "digestivo" hologram (L3).
 *
 *   node tools/holo-datos/estructuras.mjs <dir-with-downloads>
 *
 * Expects in <dir>: 1jz7.pdb (RCSB PDB, CC0), 6134.sdf (lactose), 5793.sdf (glucose), 6036.sdf
 * (galactose) — PubChem 3D conformers (public domain). Download with:
 *   curl -o 1jz7.pdb https://files.rcsb.org/download/1JZ7.pdb
 *   curl -o 6134.sdf "https://pubchem.ncbi.nlm.nih.gov/rest/pug/compound/cid/6134/record/SDF?record_type=3d"
 * Writes packages/holo/src/scenes/digestivo/estructuras.ts (C-alpha trace of chain A, the bound
 * galactose centroid as the real active site, and heavy-atom ball-and-stick of the three sugars).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const dir = resolve(process.argv[2] ?? '.');
const out = resolve(import.meta.dirname, '../../packages/holo/src/scenes/digestivo/estructuras.ts');
const r1 = (n) => Math.round(n * 10) / 10;
const r2 = (n) => Math.round(n * 100) / 100;

// --- Protein: C-alpha of chain A, in residue order ------------------------------------------
const pdb = readFileSync(join(dir, '1jz7.pdb'), 'utf8').split(/\r?\n/);
const ca = [];
const gal = [];
for (const l of pdb) {
  const rec = l.slice(0, 6).trim();
  const chain = l[21];
  if (chain !== 'A') continue;
  const xyz = [Number(l.slice(30, 38)), Number(l.slice(38, 46)), Number(l.slice(46, 54))];
  if (rec === 'ATOM' && l.slice(12, 16).trim() === 'CA' && (l[16] === ' ' || l[16] === 'A')) ca.push(xyz);
  if (rec === 'HETATM' && l.slice(17, 20) === 'GAL' && gal.length < 12) gal.push(xyz);
}
const center = ca.reduce((c, p) => [c[0] + p[0] / ca.length, c[1] + p[1] / ca.length, c[2] + p[2] / ca.length], [0, 0, 0]);
const caFlat = ca.flatMap((p) => p.map((v, i) => r1(v - center[i])));
const site = gal.reduce((c, p) => [c[0] + p[0] / gal.length, c[1] + p[1] / gal.length, c[2] + p[2] / gal.length], [0, 0, 0]).map((v, i) => r1(v - center[i]));

// --- Sugars: heavy atoms + bonds from the V2000 SDF ----------------------------------------
function sdf(file) {
  const lines = readFileSync(join(dir, file), 'utf8').split(/\r?\n/);
  const [na, nb] = [Number(lines[3].slice(0, 3)), Number(lines[3].slice(3, 6))];
  const atoms = [];
  for (let i = 0; i < na; i++) {
    const l = lines[4 + i];
    atoms.push({ x: Number(l.slice(0, 10)), y: Number(l.slice(10, 20)), z: Number(l.slice(20, 30)), e: l.slice(31, 34).trim() });
  }
  const keep = atoms.map((a, i) => (a.e === 'H' ? -1 : i)).filter((i) => i >= 0);
  const index = new Map(keep.map((i, k) => [i, k]));
  const bonds = [];
  for (let i = 0; i < nb; i++) {
    const l = lines[4 + na + i];
    const a = Number(l.slice(0, 3)) - 1;
    const b = Number(l.slice(3, 6)) - 1;
    if (index.has(a) && index.has(b)) bonds.push(index.get(a), index.get(b));
  }
  const heavy = keep.map((i) => atoms[i]);
  const c = heavy.reduce((s, a) => [s[0] + a.x / heavy.length, s[1] + a.y / heavy.length, s[2] + a.z / heavy.length], [0, 0, 0]);
  return {
    elementos: heavy.map((a) => a.e).join(''),
    xyz: heavy.flatMap((a) => [r2(a.x - c[0]), r2(a.y - c[1]), r2(a.z - c[2])]),
    enlaces: bonds,
  };
}

const lactosa = sdf('6134.sdf');
const glucosa = sdf('5793.sdf');
const galactosa = sdf('6036.sdf');

const ts = `/**
 * GENERATED by tools/holo-datos/estructuras.mjs — do not edit by hand.
 *
 * Real 3D coordinates (angstrom, centered):
 *  - PROTEINA: C-alpha trace of chain A of PDB 1JZ7, E. coli beta-galactosidase (LacZ) bound to
 *    galactose (Juers et al., 2001). An ANALOG of human lactase (same reaction: it hydrolyses the
 *    beta(1->4) bond of lactose), not the human enzyme. RCSB PDB data are CC0 (public domain).
 *  - SITIO: centroid of the galactose bound in chain A's active site, in the same frame.
 *  - Sugars: PubChem 3D conformers, heavy atoms only (CID 6134 lactose, 5793 D-glucose,
 *    6036 D-galactose). PubChem data are public domain.
 */
export interface Molecula {
  /** One letter per atom (C or O). */
  elementos: string;
  xyz: readonly number[];
  /** Pairs of atom indices. */
  enlaces: readonly number[];
}

export const PROTEINA_FUENTE = 'PDB 1JZ7 · β-galactosidasa de E. coli (análoga a la lactasa humana)';
export const PROTEINA_CA: readonly number[] = ${JSON.stringify(caFlat)};
export const SITIO_ACTIVO: readonly [number, number, number] = ${JSON.stringify(site)};
export const LACTOSA: Molecula = ${JSON.stringify(lactosa)};
export const GLUCOSA: Molecula = ${JSON.stringify(glucosa)};
export const GALACTOSA: Molecula = ${JSON.stringify(galactosa)};
`;
writeFileSync(out, ts);
console.log(`ok ${ca.length} C-alpha, site ${site}, lactosa ${lactosa.elementos.length} átomos -> ${out}`);
